-- ЛР4. Прості запити: WHERE, ORDER BY, DISTINCT
-- База: stemik (модель ЛР3 з реальними даними). Дата «сьогодні» зафіксована: 2026-11-12.
SET search_path TO stemik;

-- ------------------------------------------------------------------------------------
-- 4.1. Хто працює в студії
-- Бізнес-задача: Адміністратор складає графік чергувань: показати всіх активних
-- працівників студії з роллю й e-mail, спочатку адміністраторів, потім викладачів, за
-- прізвищем.
-- ------------------------------------------------------------------------------------
\echo '--- 4.1. Хто працює в студії'
SELECT last_name AS прізвище, first_name AS ім_я, role AS роль, email
FROM employee
WHERE active
ORDER BY CASE role WHEN 'superadmin' THEN 1 WHEN 'admin' THEN 2 ELSE 3 END,
         last_name;

-- ------------------------------------------------------------------------------------
-- 4.2. Формати й класи занять
-- Бізнес-задача: Перед плануванням розкладу на семестр з’ясувати, у яких форматах
-- проводяться заняття і в яких класах, — без повторів.
-- ------------------------------------------------------------------------------------
\echo '--- 4.2. Формати й класи занять'
SELECT DISTINCT format AS формат
FROM lesson
ORDER BY 1;

SELECT DISTINCT format AS формат, COALESCE(room, 'не вказано') AS клас
FROM lesson
ORDER BY 1, 2;

-- ------------------------------------------------------------------------------------
-- 4.3. Розклад наступного тижня
-- Бізнес-задача: Надіслати батькам розклад на наступний тиждень (16–22 листопада
-- 2026): дата, час, формат і тема кожного заняття в хронологічному порядку.
-- ------------------------------------------------------------------------------------
\echo '--- 4.3. Розклад наступного тижня'
SELECT lesson_date AS дата, to_char(start_time, 'HH24:MI') AS час,
       format AS формат, theme AS тема
FROM lesson
WHERE lesson_date BETWEEN DATE '2026-11-16' AND DATE '2026-11-22'
ORDER BY lesson_date, start_time;

-- ------------------------------------------------------------------------------------
-- 4.4. Курси для дитини 10 років
-- Бізнес-задача: Батьки телефонують: дитині 10 років, які курси їй підходять?
-- Показати активні курси, вікові межі яких охоплюють цей вік, згрупувавши за
-- напрямом.
-- ------------------------------------------------------------------------------------
\echo '--- 4.4. Курси для дитини 10 років'
SELECT direction AS напрям, name AS курс, age_min AS від, age_max AS до
FROM course
WHERE active
  AND 10 BETWEEN age_min AND age_max
ORDER BY direction, name;

-- ------------------------------------------------------------------------------------
-- 4.5. Незакриті заняття
-- Бізнес-задача: Знайти заняття, які вже минули, але викладач так і не позначив їх
-- проведеними: їх треба закрити, інакше не нарахується оплата праці. Спочатку
-- найсвіжіші.
-- ------------------------------------------------------------------------------------
\echo '--- 4.5. Незакриті заняття'
SELECT lesson_date AS дата, to_char(start_time, 'HH24:MI') AS час,
       format AS формат, theme AS тема
FROM lesson
WHERE lesson_date < DATE '2026-11-12'
  AND NOT completed
ORDER BY lesson_date DESC, start_time
LIMIT 10;

-- ------------------------------------------------------------------------------------
-- 4.6. Батьки без входу в кабінет
-- Бізнес-задача: Батьки, які жодного разу не входили в кабінет, не бачать
-- відвідування й залишку абонемента. Отримати список для розсилки інструкції зі
-- входу.
-- ------------------------------------------------------------------------------------
\echo '--- 4.6. Батьки без входу в кабінет'
SELECT last_name AS прізвище, first_name AS ім_я, phone AS телефон
FROM parent
WHERE active
  AND last_login_at IS NULL
ORDER BY last_name, first_name
LIMIT 10;
